/**
 * 把 Markdown 围栏语言字符串映射为飞书 CodeLanguage 枚举值。
 * 返回 null 表示飞书不支持该语言（如 mermaid），由调用方决定降级策略。
 */
export function mapCodeLanguage(raw: string): number | null {
  const key = raw.trim().toLowerCase();
  const name = ALIASES[key];
  if (name) return CODE_LANGUAGE[name];
  // 未知语言：尝试用原始名字直接匹配枚举名（大小写不敏感）
  const entry = Object.entries(CODE_LANGUAGE).find(([n]) => n.toLowerCase() === key);
  if (entry) return entry[1];
  return null;
}
